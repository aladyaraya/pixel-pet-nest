export const PET_BY_ID: Record<string, Pet> = Object.fromEntries(PETS.map((pet) => [pet.id, pet]))

const frameCache = new Map<string, MatrixFrame>()

/** 角色点阵帧（懒构建并缓存） */
export function petFrame(petId: string): MatrixFrame {
  const cachedFrame = frameCache.get(petId)
  if (cachedFrame) return cachedFrame
  const pet = PET_BY_ID[petId]
  if (!pet) throw new Error(`未知角色：${petId}`)
  const frame = patternToFrame(pet.pattern)
  frameCache.set(petId, frame)
  return frame
}

/** 角色特征的短回应；最多三帧、末帧回到静态。调用方负责节流和取消。 */
export function petAnimationFrames(petId: string): MatrixFrame[] {
  const base = petFrame(petId)
  const features: Record<string, [number, number, number, number, number, number]> = {
    sprout_potato: [2, 2, 13, 8, 1, 0],
    late_duck: [4, 12, 9, 16, 0, -1],
    box_ghost: [2, 3, 14, 7, 0, -1],
    nap_cloud: [12, 3, 15, 6, 0, -1],
    question_face: [5, 2, 11, 8, 1, 0],
    tiny_egg: [4, 4, 12, 11, 0, -1],
    crescent_cat: [11, 8, 15, 18, -1, 0],
    star_fawn: [2, 2, 14, 7, 0, -1],
    cape_penguin: [1, 9, 15, 14, 0, -1],
    solar_phoenix: [1, 7, 15, 14, 0, -1],
    ring_whale: [1, 2, 15, 7, 0, -1],
    moon_crown_dragon: [10, 9, 15, 15, 0, -1],
  }
  const feature = features[petId]
  if (!feature) return [base]
  const [x0, y0, x1, y1, dx, dy] = feature
  return [base, shiftFrame(base, dx, dy, { x0, y0, x1, y1 }), base]
}

/** 在指定等级内等概率抽取一个角色 id（仅在创建新局时调用一次） */
export function pickPetId(tier: PetTier): string {
  const pool = PETS.filter((pet) => pet.tier === tier)
  if (pool.length === 0) throw new Error(`该等级没有可抽取的角色：${tier}`)
  const index = Math.floor(Math.random() * pool.length)
  return pool[index].id
}
