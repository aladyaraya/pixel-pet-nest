function apply(petId: string, patches: readonly Patch[]): MatrixFrame {
  const out = [...petFrame(petId)]
  for (const [x, y, rows] of patches) rows.forEach((row, dy) => {
    for (let dx = 0; dx < row.length; dx += 1) {
      const px = x + dx, py = y + dy
      if (px <= 0 || px >= 16 || py <= 0 || py >= 22) {
        if (row[dx] === '#') throw new Error(`角色动作越出安全边距：${petId} (${px},${py})`)
      } else out[py * 17 + px] = row[dx] === '#' ? 255 : 0
    }
  })
  return out
}

function sequence(petId: string, pair: Pair): MatrixFrame[] {
  return [apply(petId, pair[0]), apply(petId, pair[1]), petFrame(petId)]
}

export function petIdleVariants(petId: string): MatrixFrame[][] {
  const drawing = drawings[petId]
  if (!drawing) throw new Error(`未知角色动作：${petId}`)
  return [sequence(petId, drawing.blink), sequence(petId, drawing.idle)]
}

export function petReactionFrames(petId: string, kind: 'tap' | 'hold'): MatrixFrame[] {
  const drawing = drawings[petId]
  if (!drawing) throw new Error(`未知角色动作：${petId}`)
  return sequence(petId, drawing[kind])
}
